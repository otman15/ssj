   private int scrambleNUS6Value(long permutations, int value) {
      int prefix = 0;
      int scrambled = 0;

      for (int level = 0; level < 6; level++) {
         int inputBit = (value >>> (5 - level)) & 1;
         int node = (1 << level) - 1 + prefix;
         int permutationBit =
               (int) ((permutations >>> node) & 1L);

         scrambled =
               (scrambled << 1)
               | (inputBit ^ permutationBit);

         prefix = (prefix << 1) | inputBit;
      }

      return scrambled;
   }
   /**
    * Builds the permutation table for all possible 6-bit input values.
    *
    * @param permutations   random vector containing the 63 permutation bits
    * @param table          stores each 6-bit input value and its corresponding scrambled value
    */
  private void buildNUS6Table(long permutations, int[] table) {
      // loop over all possible values of 6 the digits bloc that this coordinate can have
      // this can be any bloc (1to6, 7 to 12, ...)
      for (int value = 0; value < 64; value++) {
         int prefix = 0;//Store used bits to select the correct tree node
         int scrambled = 0;
         //loop over the six digits of this bloc
         for (int level = 0; level < 6; level++) {
            int inputBit = (value >>> (5 - level)) & 1;// read from the left
            int node = (1 << level) - 1 + prefix; // current node: level 1 starts at 0,2 starts at 1, 3 at 7 ,2*l - 1 + position at current level 
            int permutationBit =
                  (int) ((permutations >>> node) & 1L); // bitPermutation at this node

            scrambled =
                  (scrambled << 1)
                  | (inputBit ^ permutationBit);// build the scrambeled 6 dg

            prefix = (prefix << 1) | inputBit;// append input bit the prefix
         }

         table[value] = scrambled;
      }
   }
   
