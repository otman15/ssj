/**
 * A special case of @ref DigitalNet for the base @f$b=2@f$. The implementation
 * exploit the binary nature of computers and is much more efficient than for
 * the case of a general @f$b=2@f$. Binary expansions are easy to obtain because
 * the computer already uses them internally. The generator
 * matrices @f$\mathbf{C}_j@f$ are stored in a single large array of
 * size @f$sk@f$. The @f$c@f$-th column of @f$\mathbf{C}_j@f$,
 * for @f$c=0,\dots,k-1@f$, is stored at position @f$jk + c@f$ of this array, as
 * a 64-bit (long) integer, whose value must be less than @f$2^w@f$, where @f$k\le w \le 63@f$.
 * The @f$w@f$ least-significant bits of this integer are the entries of that column.
 * The least signifiant bit is the entry of row @f$w-1@f$, the second least significant
 * is the entry of row @f$w-2@f$, etc., and the most significant bit (which can be zero)
 * is the entry in row 0.  Often, we know that only the first @f$r < w@f$ rows of
 * the matrix are non-zero. For example, for the original Sobol points, we have @f$r=k@f$.
 * In that case, the integer that represents the column will be a multiple of @f$2^{w-r}@f$.
 * The values of @f$w@f$ cannot exceed 63 (64 is not allowed
 * because Java does not have 64-bit unsigned integers). 
 * In this class, the random digital shift in base 2 generated by
 * `addRandomShift` corresponds to a random XOR.
 * 
 * <div class="SSJ-bigskip"></div><div class="SSJ-bigskip"></div>
 */
