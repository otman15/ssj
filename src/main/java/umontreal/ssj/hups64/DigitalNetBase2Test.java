   public void rightMatrixScramble(RandomStream stream) {
      int j, c; // Dimension j, column c for new C_j.
      if (originalMat == null) {
         originalMat = genMat;
         genMat = new long[dim * numCols];
      }
      // Generate an upper triangular matrix for Faure-Tezuka right-scramble.
      // scrambleMat[c] contains column c of M.
      long[] scrambleMat = new long[outDigits];
      long boundLong = 0;
      for (c = 0; c < numCols; c++) {
         boundLong += (1 << c); // Integer repres. by string of c+1 ones.
         scrambleMat[c] = (1 | stream.nextLong(0, boundLong)) << (outDigits - c - 1);
      }
      // Right-multiply the generator matrices by the scrambling matrix.
      for (j = 0; j < dim; j++)
         rightMultiplyMat(j, scrambleMat);
   }




   /**
    * Generate a vector of `numBits <= 63` random bits using the random stream
    * `stream`.  These `numBits` bits will be the most significant ones in the 63-bit integer.
    */
   private long randomBitVectorLong(RandomStream stream, int numBits) {
      if (numBits < 1)
         throw new IllegalArgumentException("numBits must be >= 1");
      if (numBits > 63)
         throw new IllegalArgumentException("numBits must be <= 63");
      long maxj = (1L << numBits) - 1;
      return stream.nextLong(0, maxj) << (63 - numBits);
   }

